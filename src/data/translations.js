const FOLLOW_UP_KEY = Object.fromEntries(Object.entries(FOLLOW_UPS).map(([k, v]) => [v, k]))

// Translation of a question, or null (language off, or a resume question generated on the fly).
export function translateQuestion(q, lang) {
  if (!q || !T[lang]) return null
  const key = q.followUp ? FOLLOW_UP_KEY[q.text] : q.id
  return T[lang][key] || null
}

export const languageInfo = (id) => HELP_LANGUAGES.find((l) => l.id === id) || HELP_LANGUAGES[0]
